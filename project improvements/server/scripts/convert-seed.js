// Converts the MySQL seed data (../../../sql/seed.sql) into SQLite syntax (../db/seed.sql).
// Run with `npm run convert-seed -w server` after the MySQL seed changes.
// Usage: node scripts/convert-seed.js [path/to/mysql/seed.sql]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const source = path.resolve(process.argv[2] ?? path.join(here, '../../../sql/seed.sql'));
const target = path.join(here, '../db/seed.sql');

let sql = fs.readFileSync(source, 'utf8');

// Drop the MySQL header comment and USE statement; everything up to the first INSERT
sql = sql.slice(sql.indexOf('INSERT INTO'));

sql = sql
    // NOW() - INTERVAL 5 HOUR -> datetime('now', 'localtime', '-5 hours')
    .replace(/NOW\(\)\s*-\s*INTERVAL\s+(\d+)\s+(DAY|HOUR|MINUTE|SECOND)/g,
        (_, n, unit) => `datetime('now', 'localtime', '-${n} ${unit.toLowerCase()}s')`)
    // CURDATE() - INTERVAL 3 DAY -> date('now', 'localtime', '-3 days')
    .replace(/CURDATE\(\)\s*-\s*INTERVAL\s+(\d+)\s+DAY/g, (_, n) => `date('now', 'localtime', '-${n} days')`)
    .replace(/NOW\(\)/g, "datetime('now', 'localtime')")
    .replace(/CURDATE\(\)/g, "date('now', 'localtime')")
    .replace(/INSERT IGNORE/g, 'INSERT OR IGNORE')
    // Seed covers are relative to the PHP site root; the React client serves them from /images
    .replace(/'images\/covers\//g, "'/images/covers/");

const header = `-- Sample data for the SQLite database. GENERATED by scripts/convert-seed.js from ../../../sql/seed.sql;
-- edit the MySQL seed and re-run the script rather than editing this file.
-- Logins: admin / admin123, alice / password123, bob / password123, chen / password123
-- Dates are relative to the moment it is imported, so Trending and Recently Updated look fresh.

`;
fs.writeFileSync(target, header + sql);

const leftovers = sql.match(/INTERVAL|CURDATE|NOW\(\)|ON DUPLICATE/g);
console.log(`Wrote ${path.relative(process.cwd(), target)} (${(sql.length / 1024).toFixed(0)} KB)`);
if (leftovers) {
    console.warn('Warning: MySQL-only syntax is still present:', [...new Set(leftovers)].join(', '));
    process.exitCode = 1;
}
